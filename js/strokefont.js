  function widthOf(ch) {
    if (ch === " ") return 0.5;
    return WIDTH[ch] !== undefined ? WIDTH[ch] : 1;
  }

  function measureText(text, h, tracking) {
    var t = tracking === undefined ? 0.24 : tracking;
    var w = 0;
    for (var i = 0; i < text.length; i++) w += (widthOf(text[i]) + t) * h * 0.72;
    return w - t * h * 0.72;
  }

  /* Draw `text` centred on (cx, baselineY) with cap height `h`. */
  function drawText(S, text, cx, baselineY, h, opts) {
    opts = opts || {};
    var track = opts.tracking === undefined ? 0.24 : opts.tracking;
    var up = text.toUpperCase();
    var total = measureText(up, h, track);
    var x = cx - total / 2;
    var jit = opts.jit === undefined ? 0.1 : opts.jit;
    var rnd = S.rnd;

    for (var i = 0; i < up.length; i++) {
      var ch = up[i];
      var w = widthOf(ch) * h * 0.72;
      var glyph = G[ch];
      if (glyph) {
        var tilt = (rnd() - 0.5) * (opts.wave === false ? 0 : 0.09);
        var lift = (rnd() - 0.5) * h * 0.07;
        for (var s = 0; s < glyph.length; s++) {
          var pts = glyph[s].map(function (p) {
            var gx = p[0] * w;
            var gy = (p[1] - 1) * h;
            return {
              x: x + gx + gy * tilt + (rnd() - 0.5) * jit,
              y: baselineY + gy + lift + (rnd() - 0.5) * jit
            };
          });
          var smooth = pts.length > 2 ? global.PX.smooth(pts, 3, false) : pts;
          S.stroke(smooth, opts);
        }
      }
      x += w + track * h * 0.72;
    }
    return S;
  }

